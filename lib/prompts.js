const SCRIPT_SCHEMA_HINT = `{
  "scenes": [
    {
      "name": "① 破冰与开场",
      "when": "使用时机，8-14 字",
      "points": [ "话术要点1", "话术要点2", "话术要点3" ],
      "quotes": [ "直给式说法", "请教式说法", "数据式说法" ],
      "basis": "这句说法依据的 FACTS 原值"
    }
  ],
  "gaps": [ "话术中回避不了、需当面确认的事项" ]
}`;

const SCRIPT_RULES = `请生成 5 个营销场景的话术，场景固定为（name 必须原样使用）：
① 破冰与开场、② 行业趋势、③ 痛点切入、④ 产品推荐、⑤ 异议处理与收尾。

每个场景要求：
- points：恰好 3 条要点，每条不超过 30 字，讲"这通电话怎么打"，不讲产品细节。
- quotes：恰好 3 条说法，顺序固定为 直给式、请教式、数据式：
  · 直给式——直接把结论或诉求说出口，干脆；
  · 请教式——用提问把话语权交给对方，退一步；
  · 数据式——引用 FACTS 里的具体数字或资质作为切入点。
- 三条说法必须结合本客户的具体事实，检验标准是：把公司名换成同行另一家，这句话就说不通了。写不出具体事实支撑的句子，就不要写。
- quotes 里出现的每个数字、资质、年份，必须能在 FACTS 中找到原值，不得换算、不得四舍五入。
- basis 写清这句话依据的是 FACTS 的哪一项，直接引用原值。
- 礼貌称谓统一用"某总"这类泛称，不得编造真实姓名。

输出结构必须严格如下（字段名与层级不得改动）：
${SCRIPT_SCHEMA_HINT}`;

/**
 * 组装 messages。
 * @param {'report'|'script'} task
 * @param {{company:string, facts:object, industry?:string}} payload
 */
function buildMessages(task, payload) {
  const facts = payload.facts && typeof payload.facts === 'object' ? payload.facts : {};
  const factsText = JSON.stringify(facts, null, 2);

  const taskBlock =
    task === 'report'
      ? `任务：生成访前画像报告。\n\n【输出结构】\n${REPORT_RULES}`
      : `任务：生成营销话术。\n\n【输出结构】\n${SCRIPT_RULES}`;

  const user = `【企业】${payload.company || '（未提供）'}

【FACTS】（这是唯一允许使用的事实来源）
${factsText}

${taskBlock}

再次强调：只输出 JSON 对象本身。FACTS 里没有的信息一律用占位符加 🔴 待客户经理补充，不得编造。`;

  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user }
  ];
}

module.exports = { SYSTEM, BANNED, buildMessages, REPORT_SCHEMA_HINT, SCRIPT_SCHEMA_HINT };
